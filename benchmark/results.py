#!/usr/bin/env python3
"""Every number in results.md, computed from the SYNERGY+ data and the committed answers (no API calls).

  results.py                    check the data against data-manifest.json, then write results.md
  results.py --check            exit 1 if results.md is not what the data and answers give (used by the tests)
  results.py --write-manifest   record the data this benchmark was run on (review sizes, include counts, label hashes)

Sections: frozen calibration; the 23 test reviews at the frozen thresholds and at the corrected ones; leave-one-review-out
over all 43 answered reviews; title/abstract-stage labels; ASReview 3.0.8; stopping rules; run-to-run stability; cost."""
import hashlib
import json
import random
import statistics
import sys

import common

OUT = common.HERE / "results.md"
README = common.HERE.parent / "README.md"
EVIDENCE = common.HERE.parent / "src/sievesafe/evidence.txt"
START, END = "<!-- benchmark:start (generated by benchmark/results.py) -->", "<!-- benchmark:end -->"


def manifest() -> dict:
    out = {}
    for k in common.meta():
        recs = common.records(k)
        rows = "\n".join(f"{r['id']}\t{r['y']}\t{'' if r['ya'] is None else r['ya']}" for r in recs)
        out[k] = {"n": len(recs), "includes": sum(r["y"] for r in recs), "sha256": hashlib.sha256(rows.encode()).hexdigest()}
    return out


if "--write-manifest" in sys.argv:
    common.MANIFEST.write_text(json.dumps(manifest(), indent=1, sort_keys=True) + "\n")
    sys.exit(f"wrote {common.MANIFEST.name}")
expected, found = json.loads(common.MANIFEST.read_text()), manifest()
if bad := sorted(k for k in expected.keys() | found.keys() if expected.get(k) != found.get(k)):
    sys.exit(f"the data in {common.DATA} differs from data-manifest.json in {len(bad)} reviews ({', '.join(bad[:5])}); see README")

meta = common.meta()
frozen = json.loads(common.CALIBRATION.read_text())
corrected = common.calibrate()
T = {k: v["threshold"] for k, v in frozen["targets"].items()}
TC = {k: v["threshold"] for k, v in corrected["targets"].items()}
SAFE, SAFE_C = T["100%"], TC["100%"]
test = {k: common.scored(common.TEST, k) for k in common.test_keys()}
train = {k: common.scored(common.TRAIN, k, common.TRAIN_CAP) for k in common.train_keys()}
missing = [k for k, v in test.items() if len(v) != int(meta[k]["n_records"])]
if missing:
    sys.exit(f"test answers incomplete for {missing}; run screen.py f1 test")
L: list[str] = []
pct = lambda x: f"{x:.0%}"
pct1 = lambda x: f"{x:.1%}"


def at(rows: list[dict], t: float, label: str = "y") -> tuple[float, float]:
    """(recall of `label`, weighted share of records below t)."""
    P = sum(r[label] or 0 for r in rows)
    return (sum(r[label] or 0 for r in rows if r["s"] >= t) / P if P else float("nan"),
            1 - sum(r.get("w", 1.0) for r in rows if r["s"] >= t) / sum(r.get("w", 1.0) for r in rows))


def table(head: list[str], rows: list[list], align: str) -> None:
    L.append("| " + " | ".join(head) + " |")
    L.append("|" + "|".join(":--" if a == "l" else "--:" for a in align) + "|")
    L.extend("| " + " | ".join(str(c) for c in r) + " |" for r in rows)
    L.append("")


# --- header and calibration
pooled_test = [r for v in test.values() for r in v]
P = sum(r["y"] for r in pooled_test)
L += ["# sievesafe benchmark results", "",
      "Generated by `benchmark/results.py` from SYNERGY+ v3 and the committed answers; do not edit by hand.", "",
      (f"- Test answers sha256 `{common.answers_sha(common.TEST)[:12]}`, train answers sha256 `{frozen['answers_sha256'][:12]}`, "
       f"data manifest sha256 `{hashlib.sha256(common.MANIFEST.read_bytes()).hexdigest()[:12]}`"),
      f"- Test split: {len(test)} reviews, {len(pooled_test):,} records, {P} included studies (final, full-text labels)",
      (f"- Train split used for calibration: {len(train)} reviews, {frozen['records']:,} records "
       f"(capped at {common.TRAIN_CAP:,} per review, weighted), {frozen['includes']} included studies"), "",
      "## 1. Calibration (train reviews only)", "",
      (f"Frozen at {frozen['frozen_at']}, before the test split was scored against its labels. The frozen run looked scores up by "
       f"OpenAlex id pooled across train reviews, so {corrected['id_pooling_changed']['records']} records "
       f"({corrected['id_pooling_changed']['includes']} of them includes) that appear in two reviews carried the other review's score; "
       "`calibrate.py --as-frozen` reproduces the frozen file exactly, `calibrate.py` gives the corrected thresholds. "
       f"sievesafe uses the frozen safe threshold ({SAFE})."), ""]
table(["train recall target", "frozen threshold", "train recall", "train auto-excluded", "corrected threshold", "train recall", "train auto-excluded"],
      [[k, T[k], pct1(frozen["targets"][k]["train_recall"]), pct(frozen["targets"][k]["train_auto_excluded"]), TC[k],
        pct1(corrected["targets"][k]["train_recall"]), pct(corrected["targets"][k]["train_auto_excluded"])] for k in T], "lrrrrrr")

# --- test split
L += ["## 2. Test split (23 reviews, final labels)", "",
      ("Recall = share of the finally included studies scoring at or above the threshold; auto-excluded = share of all records "
       "below it. WSS@95 = share of records not read, reading in score order, when 95% of the includes are found, minus 0.05."), ""]
rows = []
for k, v in test.items():
    order = common.ranked(v)
    cells = [f"{pct(r)} / {pct(e)}" for r, e in (at(v, t) for t in (*T.values(), SAFE_C))]
    rows.append([k, len(v), sum(order), f"{common.auc([r['s'] for r in v], [r['y'] for r in v]):.3f}",
                 f"{common.wss(order, len(v), sum(order), 0.95):.3f}", *cells])
rows.append(["**pooled**", f"{len(pooled_test):,}", P, f"{common.auc([r['s'] for r in pooled_test], [r['y'] for r in pooled_test]):.3f}", "",
             *[f"**{pct(r)} / {pct(e)}**" for r, e in (at(pooled_test, t) for t in (*T.values(), SAFE_C))]])
table(["review", "records", "includes", "AUC", "WSS@95", *[f"t={t} ({k}) recall / auto-excl." for k, t in T.items()],
       f"t={SAFE_C} (corrected 100%)"], rows, "lrrrrrrrr")
per = {t: [at(v, t) for v in test.values()] for t in (*T.values(), SAFE_C)}
L += [(f"Median per review: AUC {statistics.median(common.auc([r['s'] for r in v], [r['y'] for r in v]) for v in test.values()):.3f}, "
       f"WSS@95 {statistics.median(common.wss(common.ranked(v), len(v), sum(r['y'] for r in v), 0.95) for v in test.values()):.3f}."), ""]
table(["threshold", "reviews with 100% recall", "reviews with ≥98% recall", "lowest review recall", "pooled recall", "auto-excluded (pooled)",
       "auto-excluded (mean per review)"],
      [[f"{t}" + (" (safe, frozen)" if t == SAFE else " (safe, corrected)" if t == SAFE_C else ""), f"{sum(r == 1 for r, _ in per[t])}/{len(test)}",
        f"{sum(r >= 0.98 for r, _ in per[t])}/{len(test)}", pct(min(r for r, _ in per[t])), pct1(at(pooled_test, t)[0]), pct(at(pooled_test, t)[1]),
        pct(statistics.mean(e for _, e in per[t]))] for t in (*T.values(), SAFE_C)], "lrrrrrr")

# --- leave one review out
reviews = {**{k: v for k, v in train.items()}, **test}
L += ["## 3. Leave one review out (43 reviews)", "",
      ("For each review, the threshold is recalibrated on the other 42 (pooled recall of their includes meets the target) and applied "
       "to the held-out one. The 20 train reviews are capped and weighted as in calibration; the 23 test reviews are complete. "
       "Upper bound: Clopper–Pearson one-sided 95% bound on the share of future reviews that would lose at least one include."), ""]
rows = []
for target in (1.0, 0.98, 0.95):
    res = []
    for held, v in reviews.items():
        t = common.threshold([(r["s"], r["y"]) for k, o in reviews.items() if k != held for r in o], target)
        res.append((held, t, *at(v, t)))
    fails = sum(r[2] < 1 for r in res)
    worst = min(res, key=lambda r: r[2])
    if target == 1.0:
        loro = {"n": len(res), "full": len(res) - fails, "ge98": sum(r[2] >= 0.98 for r in res), "upper": common.cp_upper(fails, len(res)),
                "t": (min(r[1] for r in res), max(r[1] for r in res)), "excluded": statistics.mean(r[3] for r in res)}
    rows.append([pct(target), f"{min(r[1] for r in res)}–{max(r[1] for r in res)} (median {statistics.median(r[1] for r in res)})",
                 f"{len(res) - fails}/{len(res)}", f"{sum(r[2] >= 0.98 for r in res)}/{len(res)}", pct(common.cp_upper(fails, len(res))),
                 f"{pct1(statistics.mean(r[2] for r in res))} (min {pct(worst[2])}, {worst[0]})",
                 f"{pct(statistics.mean(r[3] for r in res))} (median {pct(statistics.median(r[3] for r in res))})"])
table(["recall target", "threshold range", "reviews with 100% recall", "reviews with ≥98% recall", "upper bound on reviews losing an include",
       "recall mean", "auto-excluded mean"], rows, "lrrrrrr")

# --- title/abstract labels
abs_reviews = {k: v for k, v in test.items() if any(r["ya"] is not None for r in v)}
L += ["## 4. Against title/abstract-stage decisions", "",
      (f"{len(abs_reviews)} of the test reviews also publish the human title/abstract decision. Recall here = share of the records "
       "humans passed to full text that score at or above the threshold. Lost = those below it; the last column counts how many of the "
       "lost ones were finally included."), ""]
rows = []
for k, v in abs_reviews.items():
    lost = [r for r in v if r["ya"] and r["s"] < SAFE]
    rows.append([k, sum(r["ya"] or 0 for r in v), pct(at(v, SAFE, "ya")[0]), pct(at(v, SAFE_C, "ya")[0]), len(lost), sum(r["y"] for r in lost)])
ra, rc = [at(v, SAFE, "ya")[0] for v in abs_reviews.values()], [at(v, SAFE_C, "ya")[0] for v in abs_reviews.values()]
rows.append(["**mean (min)**", "", f"**{pct(statistics.mean(ra))} ({pct(min(ra))})**", f"**{pct(statistics.mean(rc))} ({pct(min(rc))})**",
             sum(r[4] for r in rows), sum(r[5] for r in rows)])
table(["review", "passed by humans", f"recall at t={SAFE}", f"recall at t={SAFE_C}", f"lost at t={SAFE}", "of which finally included"], rows, "lrrrrr")

# --- ASReview
asr = json.loads((common.ANSWERS / "asreview-3.0.8.json").read_text())
L += ["## 5. Ranking against ASReview 3.0.8", "",
      ("ASReview: `asreview simulate` with its default model, 1 included + 1 excluded prior record, seeds 1–3, mean over seeds. "
       "Jev: one zero-shot ranking, no labels. WSS@100 = share of records not read when every include is found."), ""]


def wss_positions(pos: list[int], n: int, inc: int, target: float) -> float:
    hits = set(pos)
    return common.wss([1 if i in hits else 0 for i in range(1, max(pos) + 1)], n, inc, target)


rows, cmp = [], []
for k, v in test.items():
    n, inc = int(meta[k]["n_records"]), int(meta[k]["n_records_included"])
    a95 = statistics.mean(wss_positions(p, n, inc, 0.95) for p in asr[k].values())
    a100 = statistics.mean(wss_positions(p, n, inc, 1.0) for p in asr[k].values())
    order = common.ranked(v)
    j95, j100 = common.wss(order, n, inc, 0.95), common.wss(order, n, inc, 1.0)
    cmp.append((a95, a100, j95, j100))
    rows.append([k, n, inc, f"{a95:.3f}", f"{j95:.3f}", f"{a100:.3f}", f"{j100:.3f}"])
med = [statistics.median(c[i] for c in cmp) for i in range(4)]
rows.append(["**median**", "", "", f"**{med[0]:.3f}**", f"**{med[2]:.3f}**", f"**{med[1]:.3f}**", f"**{med[3]:.3f}**"])
table(["review", "records", "includes", "ASReview WSS@95", "Jev WSS@95", "ASReview WSS@100", "Jev WSS@100"], rows, "lrrrrrr")
L += [f"Jev ≥ ASReview on WSS@95 in {sum(c[2] >= c[0] for c in cmp)}/{len(cmp)} reviews; on WSS@100 in {sum(c[3] >= c[1] for c in cmp)}/{len(cmp)}.", ""]

# --- stopping rules
L += ["## 6. Stopping rules on the Jev ranking (final labels)", "",
      (f"safe = read every record scoring ≥ {SAFE}; knee = Cormack & Grossman (2016) knee method (≥150 read, slope ratio ≥ 6, "
       "10% margin); safe+knee = whichever stops first."), ""]
stops = {"safe": [], "knee": [], "safe+knee": []}
for v in test.values():
    order = common.ranked(v)
    n, inc = len(order), sum(order)
    k_safe, k_knee = sum(r["s"] >= SAFE for r in v), common.knee_stop(order)
    for name, k in (("safe", k_safe), ("knee", k_knee), ("safe+knee", min(k_safe, k_knee))):
        stops[name].append((sum(order[:k]) / inc, 1 - k / n))
table(["rule", "recall mean", "recall min", "reviews 100%", "reviews ≥98%", "not read (mean)", "not read (median)"],
      [[name, pct1(statistics.mean(r for r, _ in v)), pct1(min(r for r, _ in v)), f"{sum(r == 1 for r, _ in v)}/{len(v)}",
        f"{sum(r >= 0.98 for r, _ in v)}/{len(v)}", pct(statistics.mean(u for _, u in v)), pct(statistics.median(u for _, u in v))]
       for name, v in stops.items()], "lrrrrrr")

# --- stability
stab = [json.loads(line) for f in common.answer_files("stability", "jev-1.13.0") for line in common.read_lines(f)]
pool = [(k, r) for k in test for r in test[k]]
sample = random.Random(1).sample(pool, len(stab))
assert all(abs(s["old"] - r["s"]) < 1e-12 for s, (_, r) in zip(stab, sample)), "stability answers do not match their seeded sample"
old, new = [s["old"] for s in stab], [s["new"] for s in stab]
mo, mn = statistics.mean(old), statistics.mean(new)
corr = sum((a - mo) * (b - mn) for a, b in zip(old, new)) / (sum((a - mo) ** 2 for a in old) * sum((b - mn) ** 2 for b in new)) ** 0.5
L += ["## 7. Run-to-run stability", "",
      (f"{len(stab):,} test records drawn at random (seed 1) and asked again with the model pinned to `{stab[0]['model']}`, compared with "
       f"their test-split answers. Correlation {corr:.3f}; mean absolute change {statistics.mean(abs(a - b) for a, b in zip(old, new)):.3f} "
       f"(max {max(abs(a - b) for a, b in zip(old, new)):.2f})."), ""]
table(["threshold", "records crossing it", "of which included studies"],
      [[t, f"{(c := sum((a >= t) != (b >= t) for a, b in zip(old, new)))} ({pct1(c / len(stab))})",
        sum(r["y"] for s, (_, r) in zip(stab, sample) if (s["old"] >= t) != (s["new"] >= t))] for t in sorted({SAFE, SAFE_C, T["98%"]})], "rrr")

# --- cost
f1_calls = common.calls(common.TEST)
tok = sum(c["usage"]["input_tokens"] for c in f1_calls)
ms = sorted(c["ms"] for c in f1_calls)
L += ["## 8. Cost and latency (test split)", "",
      (f"{len(f1_calls):,} calls (one per record), {tok / len(f1_calls):,.0f} input tokens per record, US$ {tok * common.PRICE_PER_TOKEN:.2f} in total "
       f"(US$ {tok * common.PRICE_PER_TOKEN / len(f1_calls):.6f} per record, at US$ 0.042 per million input tokens); median latency {ms[len(ms) // 2]} ms per call."), ""]

# --- the README's headline block, so its numbers are generated too
safe_rec, safe_exc = at(pooled_test, SAFE)
lost_final = sum(r["y"] for v in abs_reviews.values() for r in v if r["ya"] and r["s"] < SAFE)
H = [START, "",
     f"| on {len(test)} held-out SYNERGY+ reviews ({len(pooled_test):,} records) | sievesafe (zero-shot, no labels) | ASReview 3.0.8 (active learning, 1+1 labelled priors) |",
     "|:--|--:|--:|",
     f"| work saved at 95% recall (median WSS@95) | **{med[2]:.3f}** | {med[0]:.3f} |",
     f"| work saved at 100% recall (median WSS@100) | **{med[3]:.3f}** | {med[1]:.3f} |",
     (f"| reviews where sievesafe saves as much or more (WSS@95 / WSS@100) | {sum(c[2] >= c[0] for c in cmp)}/{len(cmp)} / "
      f"{sum(c[3] >= c[1] for c in cmp)}/{len(cmp)} | |"), "",
     f"| safe threshold ({SAFE}), frozen on {len(train)} other reviews | |",
     "|:--|--:|",
     f"| records below it (flagged in rank mode, removed in exclude mode) | {pct(safe_exc)} of {len(pooled_test):,} |",
     (f"| finally included studies below it | {sum(r['y'] for r in pooled_test if r['s'] < SAFE)} of {P} (recall {pct(safe_rec)} in "
      f"{sum(r == 1 for r, _ in per[SAFE])}/{len(test)} reviews) |"),
     (f"| leave-one-review-out, {loro['n']} reviews: reviews keeping ≥98% / 100% of their includes | {loro['ge98']}/{loro['n']} / {loro['full']}/{loro['n']} "
      f"(threshold {loro['t'][0]}–{loro['t'][1]}; 95% upper bound on reviews losing any include: {pct(loro['upper'])}) |"),
     (f"| records humans passed at title/abstract stage kept above it ({len(abs_reviews)} reviews) | {pct(statistics.mean(ra))} on average "
      f"(lowest {pct(min(ra))}); of the rest, {lost_final} finally included |"),
     f"| run-to-run correlation of scores (model pinned) | {corr:.3f} |",
     f"| cost | about US$ {1000 * tok * common.PRICE_PER_TOKEN / len(f1_calls):.2f} per 1,000 records |", "", END]
readme = README.read_text()
if START not in readme or END not in readme:
    sys.exit(f"README.md has no {START} … {END} block")
readme = readme[:readme.index(START)] + "\n".join(H) + readme[readme.index(END) + len(END):]
ab_lo, ab_hi = min(ra), max(ra)
evidence = (f"On the SYNERGY+ benchmark (v3), with the threshold frozen on {len(train)} other reviews, records scoring below it in the "
            f"{len(test)} test reviews ({len(pooled_test):,} records, {P} included studies) contained "
            + (f"{P - round(safe_rec * P)} of the finally included studies" if safe_rec < 1 else "none of the studies finally included in any of them")
            + f", while {pct(safe_exc)} of all records fell below it. Recalibrating with each of {loro['n']} reviews held out in turn kept "
            f"≥98% of included studies in {loro['ge98']} of {loro['n']} reviews and all of them in {loro['full']}. Against human title/abstract "
            f"decisions the threshold is stricter: it kept {pct(statistics.mean(ra))} of the records humans passed at that stage "
            f"(range {pct(ab_lo).rstrip('%')}–{pct(ab_hi)}, {len(abs_reviews)} reviews), and "
            + ("none of the records it lost was finally included." if lost_final == 0 else f"{lost_final} of the records it lost were finally included.")
            + "\n")

text = "\n".join(L)
if "--check" in sys.argv:
    stale = [f.name for f, t in ((OUT, text), (README, readme), (EVIDENCE, evidence)) if not f.exists() or f.read_text() != t]
    sys.exit(f"stale: {', '.join(stale)}; run benchmark/results.py" if stale else 0)
OUT.write_text(text)
README.write_text(readme)
EVIDENCE.write_text(evidence)
print(f"wrote {OUT.relative_to(common.HERE.parent)}, the numbers block of README.md and src/sievesafe/evidence.txt")
